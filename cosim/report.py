#!/usr/bin/env python3
"""Summarise the system co-simulation (cosim/run.sh) into docs/cosim.md.

  python3 cosim/report.py [out/cosim] [out/cosim/bpsim.tsv]

Aggregates as in explore/sweep.py: speedup = geometric mean over programs of (static not-taken cycles / cycles);
accuracy = mean over programs.  embench.nbody and embench.cubic are reported separately (docs/exploration.md 1).
"""
import csv, glob, math, os, sys

EXCLUDE = {"embench.nbody", "embench.cubic"}
DRV = ["default", "bimodal", "gshare", "tournament", "static not-taken (through the chip)"]
PK = ["mis_def", "mis_bim", "mis_gsh", "mis_trn"]


def kv(path):
    d = {}
    for t in open(path).read().split():
        if "=" in t:
            k, v = t.split("=", 1)
            try:
                d[k] = float(v) if "." in v else int(v)
            except ValueError:
                d[k] = v
    return d


def split(programs):
    fam = {}
    for p in sorted(programs):
        fam.setdefault(p.split(".")[0], []).append(p)
    hold = {p for ps in fam.values() for i, p in enumerate(ps) if i % 4 == 2}
    return set(programs) - hold, hold


def gmean(xs):
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def main():
    O = sys.argv[1] if len(sys.argv) > 1 else "out/cosim"
    bp = sys.argv[2] if len(sys.argv) > 2 else os.path.join(O, "bpsim.tsv")
    progs = sorted(os.path.basename(f)[:-len(".d0.txt")] for f in glob.glob(os.path.join(O, "*.d0.txt")))
    R = {}
    for p in progs:
        try:
            R[p] = dict(d=[kv(f"{O}/{p}.d{i}.txt") for i in range(5)], seq=kv(f"{O}/{p}.seq.txt"),
                        m0=kv(f"{O}/{p}.d0.model.txt"), ms=kv(f"{O}/{p}.seq.model.txt"))
        except FileNotFoundError as e:
            print("incomplete:", p, e)
    progs = [p for p in progs if p in R]
    main_set = [p for p in progs if p not in EXCLUDE]
    tune, hold = split(set(main_set))
    L = []
    w = L.append
    w("# BPX-1 system co-simulation: results (VR-06, VR-01 on programs, PF-01 to PF-03)\n")
    w("Generated by `cosim/report.py` from `bash cosim/run.sh`; every number is measured on the RTL (Verilated")
    w("`bpx_chip`, behavioural table model `BPX_BEHAV`) driven through its pins by the U1 CPU contract of")
    w("docs/SPEC.md section 9. Method and reading: docs/verification.md.\n")
    dual = R[progs[0]]["d"][0].get("dual", 0)
    if os.path.basename(os.path.normpath(O)) == "cosim_safe":
        w("**Safe mode of the default predictor: CTRL[15:12] = 0 (plain hashed perceptron: no reference inputs, no negation, "
          "fixed threshold).** The cross-check of section 6 compares with the full default predictor and does not apply here.")
    w("")
    w(f"**Adapter mode: {'two requests per CPU cycle where needed (SPEC 9, rule 7)' if dual else 'one request per CPU cycle'}**, "
      f"{R[progs[0]]['d'][0]['K']} chip clocks per CPU cycle.\n")

    # ---- bit-exactness
    nreq = sum(R[p]["m0"]["requests"] + R[p]["ms"]["requests"] for p in progs)
    mism = sum(R[p]["m0"]["mismatches"] + R[p]["ms"]["mismatches"] for p in progs)
    errs = sum(R[p]["d"][i]["errors"] for p in progs for i in range(5)) + sum(R[p]["seq"]["errors"] for p in progs)
    stat_bad = [p for p in progs if any(R[p]["d"][0][k] != R[p]["m0"][k] for k in PK + ["resolved"]) or
                any(R[p]["seq"][k] != R[p]["ms"][k] for k in PK + ["resolved"])]
    w("## 1. RTL against the golden model (VR-01)\n")
    w(f"- Programs: {len(progs)}; requests replayed through the golden model: {nreq:,} (U1 in-flight run with the default")
    w("  predictor driving, and the one-in-flight trace replay).")
    w(f"- Reply mismatches (prediction or confidence): **{mism}**.")
    w(f"- Programs whose chip statistics differ from the model's: **{len(stat_bad)}** {stat_bad if stat_bad else ''}.")
    w(f"- Protocol errors counted by the chip over all runs: **{errs}**.\n")

    # ---- aggregate
    def agg(ps, i):
        sp = gmean([R[p]["d"][i]["snt_cycles"] / R[p]["d"][i]["cycles"] for p in ps])
        if i < 4:
            acc = [100 * (1 - R[p]["d"][i][PK[i]] / max(R[p]["d"][i]["branches"], 1)) for p in ps]
            wi = min(range(len(ps)), key=lambda j: acc[j])
            return sp, sum(acc) / len(acc), acc[wi], ps[wi]
        acc = [100 * (1 - R[p]["d"][i]["mis_drive"] / max(R[p]["d"][i]["branches"], 1)) for p in ps]
        return sp, sum(acc) / len(acc), min(acc), ""
    w("## 2. Speedup and accuracy with each predictor driving (O1, O2, PF-01, PF-02)\n")
    w(f"{len(main_set)} programs; speedup over the same CPU with static not-taken and no chip; accuracy of the driving predictor")
    w("in its own run (U1 in-flight depth, wrong-path requests included in training as on the real CPU).\n")
    w("| Driving predictor | Speedup, all | tuning | held-out | Accuracy, all | tuning | held-out | Worst program |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for i in range(5):
        a, t, h = agg(main_set, i), agg(sorted(tune), i), agg(sorted(hold), i)
        w(f"| {DRV[i]} | **{a[0]:.4f}** | {t[0]:.4f} | {h[0]:.4f} | **{a[1]:.2f} %** | {t[1]:.2f} % | {h[1]:.2f} % | {a[2]:.2f} % {a[3]} |")
    w("")
    tot = lambda i: sum(R[p]["d"][i]["cycles"] for p in main_set)
    snt = sum(R[p]["d"][0]["snt_cycles"] for p in main_set)
    w(f"Total cycles over the set: static not-taken {snt:,}; " + "; ".join(f"{DRV[i].split(' (')[0]} {tot(i):,}" for i in range(5)) + ".\n")

    # ---- PF-02 per program
    worse, worse_sp = [], []
    for p in main_set:
        d = R[p]["d"]
        br = max(d[0]["branches"], 1)
        own = [100 * (1 - d[i][PK[i]] / br) for i in range(4)]
        bi = max(range(1, 4), key=lambda i: own[i])
        if own[0] < own[bi]:
            worse.append((own[0] - own[bi], p, own[0], own[bi], DRV[bi]))
        cb = min(range(1, 4), key=lambda i: d[i]["cycles"])
        if d[0]["cycles"] > d[cb]["cycles"]:
            worse_sp.append((d[0]["cycles"] / d[cb]["cycles"] - 1, p, DRV[cb]))
    w("## 3. Programs where the default predictor is worse than the best reference (PF-02)\n")
    if worse:
        w("| Program | Default | Best reference | Difference |")
        w("| --- | --- | --- | --- |")
        for dlt, p, a, b, n in sorted(worse):
            w(f"| {p} | {a:.2f} % | {b:.2f} % ({n}) | {dlt:+.2f} points |")
    else:
        w("None: on every program the default predictor, driving, is at least as accurate as each reference predictor driving.")
    w("")
    if worse_sp:
        w("Programs where the default-driven run takes more cycles than the best reference-driven run: " +
          ", ".join(f"{p} (+{100 * x:.2f} %, {n})" for x, p, n in sorted(worse_sp, reverse=True)) + ".\n")
    else:
        w("On no program does the default-driven run take more cycles than a reference-driven run.\n")

    # ---- PF-03
    w("## 4. In-flight depth against one-in-flight (PF-03)\n")
    a_in = [100 * (1 - R[p]["d"][0]["mis_def"] / max(R[p]["d"][0]["branches"], 1)) for p in main_set]
    a_sq = [100 * (1 - R[p]["seq"]["mis_def"] / max(R[p]["seq"]["branches"], 1)) for p in main_set]
    dl = sorted((a_in[j] - a_sq[j], main_set[j]) for j in range(len(main_set)))
    w(f"Default predictor, mean accuracy over {len(main_set)} programs: **{sum(a_in) / len(a_in):.2f} %** in the CPU run (up to")
    w(f"{max(R[p]['d'][0]['peak_inflight'] for p in main_set)} branches in flight), **{sum(a_sq) / len(a_sq):.2f} %** with one in flight. Largest loss: {dl[0][1]} ({dl[0][0]:+.2f} points);")
    w(f"largest gain: {dl[-1][1]} ({dl[-1][0]:+.2f} points); programs losing more than 0.5 points: {sum(1 for x in dl if x[0] < -0.5)}.\n")

    # ---- latency / throughput
    w("## 5. Latency and throughput in the CPU runs (O3)\n")
    rq = sum(R[p]["d"][i]["requests"] for p in progs for i in range(5))
    h = {k: sum(R[p]["d"][i][k] for p in progs for i in range(5)) for k in ("lat3", "lat4", "lat5", "lat6p", "late")}
    K = R[progs[0]]["d"][0]["K"]
    w(f"{rq:,} requests at {K} chip clocks per CPU cycle: acknowledged after 3 clocks {100 * h['lat3'] / rq:.2f} %, 4 clocks {100 * h['lat4'] / rq:.2f} %,")
    w(f"5 clocks {100 * h['lat5'] / rq:.2f} %, 6 or more {100 * h['lat6p'] / rq:.2f} %; answers later than the CPU cycle: **{h['late']}**.")
    um = max(R[p]["d"][i].get("used_max", 0) for p in progs for i in range(5))
    pr = sum(R[p]["d"][i].get("pairs", 0) for p in progs for i in range(5))
    w(f"Most chip clocks used by the requests of one CPU cycle: {um}; CPU cycles with two requests: {pr:,}.")
    wp = sum(R[p]["d"][0]["wrongpath_predicts"] for p in main_set)
    w(f"Wrong-path predicts in the default-driven runs: {wp:,} ({100 * wp / sum(R[p]['d'][0]['branches'] for p in main_set):.2f} % of branches).\n")

    # ---- cross-check with the exploration simulator
    if os.path.exists(bp):
        B = {}
        for r in csv.DictReader(open(bp), delimiter="\t"):
            B[(r["config"], r["program"])] = r
        names = ["def", "bim", "gsh", "trn"]
        w("## 6. Cross-check against the exploration simulator (`explore/bpsim`)\n")
        w("The simulator that chose the design models the same CPU without the rule that a misprediction is reported")
        w("alone (docs/SPEC.md 9), so its cycle counts are a lower bound.\n")
        w("| Driving predictor | Speedup: RTL co-simulation | exploration simulator | Accuracy: RTL | simulator | Programs with equal mispredictions |")
        w("| --- | --- | --- | --- | --- | --- |")
        for i, n in enumerate(names):
            ps = [p for p in main_set if (n, p) in B]
            if not ps:
                continue
            sp_b = gmean([int(B[(n, p)]["snt_cycles"]) / int(B[(n, p)]["cycles"]) for p in ps])
            ac_b = sum(100 * (1 - int(B[(n, p)]["mis_cpu"]) / max(int(B[(n, p)]["branches"]), 1)) for p in ps) / len(ps)
            a = agg(ps, i)
            eq = sum(1 for p in ps if int(B[(n, p)]["mis_cpu"]) == R[p]["d"][i][PK[i]])
            w(f"| {DRV[i]} | {a[0]:.4f} | {sp_b:.4f} | {a[1]:.2f} % | {ac_b:.2f} % | {eq} of {len(ps)} |")
        w("")
        sb = [p for p in main_set if ("def", p) in B and int(B[("def", p)]["snt_cycles"]) != R[p]["d"][0]["snt_cycles"]]
        sq = [p for p in main_set if ("def", p) in B and int(B[("def", p)]["mis_seq"]) != R[p]["seq"]["mis_def"]]
        w(f"Static not-taken cycle counts differ on {len(sb)} programs; one-in-flight mispredictions of the default")
        w(f"predictor differ on {len(sq)} programs.\n")

    # ---- excluded programs
    ex = [p for p in progs if p in EXCLUDE]
    if ex:
        w("## 7. Programs outside the aggregates\n")
        w("| Program | Speedup default | bimodal | gshare | tournament | Accuracy default | bimodal | gshare | tournament |")
        w("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for p in ex:
            d = R[p]["d"]
            w(f"| {p} | " + " | ".join(f"{d[i]['snt_cycles'] / d[i]['cycles']:.4f}" for i in range(4)) + " | " +
              " | ".join(f"{100 * (1 - d[i][PK[i]] / max(d[i]['branches'], 1)):.2f} %" for i in range(4)) + " |")
        w("")

    # ---- per program
    w("## 8. Every program\n")
    w("Cycles with each predictor driving; accuracy of each predictor in the default-driven run; default one-in-flight.\n")
    w("| Program | Branches | Static NT cycles | default | bimodal | gshare | tournament | Acc. default | bimodal | gshare | tournament | default, one in flight |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for p in progs:
        d = R[p]["d"]
        br = max(d[0]["branches"], 1)
        w(f"| {p} | {d[0]['branches']:,} | {d[0]['snt_cycles']:,} | " + " | ".join(f"{d[i]['cycles']:,}" for i in range(4)) + " | " +
          " | ".join(f"{100 * (1 - d[0][k] / br):.2f}" for k in PK) + f" | {100 * (1 - R[p]['seq']['mis_def'] / max(R[p]['seq']['branches'], 1)):.2f} |")
    w("")
    safe = os.path.basename(os.path.normpath(O)) == "cosim_safe"       # run with BPX_FEAT=0
    out = "docs/cosim_safe.md" if safe else "docs/cosim_dual.md" if dual else "docs/cosim.md"
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print("\n".join(L[:60]))
    print("wrote", out, len(progs), "programs")


if __name__ == "__main__":
    main()
